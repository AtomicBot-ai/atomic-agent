function resolveDefaultGrammarsDir(): string {
  const nextToBinary = join(dirname(process.execPath), "grammars");
  if (existsSync(nextToBinary)) {
    return nextToBinary;
  }
  const here = dirname(fileURLToPath(import.meta.url));
  return resolve(here, "../../../grammars");
}

export interface BuildGrammarOptions {
  /**
   * Optional pre-built `mcp-server-tool ::= ...` line. Generated by
   * `buildMcpToolNameRule(McpManager.listAllToolMeta())` after every
   * connect / disconnect. When `null` / omitted, the static
   * permissive placeholder in `tool-call.gbnf` survives — so a
   * grammar rebuild only invalidates the KV cache when the dynamic
   * list of MCP tool names actually changed.
   */
  mcpToolNameRule?: string | null;
  /**
   * Master switch for the interactive `browser.*` tool surface. When
   * `false`, the `browser-tool` alternative is structurally removed from
   * the `tool-name` rule so the constrained sampler can never emit a
   * `browser.*` call — the live browser is unreachable even if a stale
   * descriptor or persona line still names it. Mirrors
   * `config.browser.enabled`; default `true` keeps the static grammar
   * untouched (byte-stable KV cache).
   */
  browserEnabled?: boolean;
  /**
   * `localModels.reasoningBudgetTokens`: how far the reasoning prelude
   * may run before the grammar admits only the close sentinel, in
   * tokens (`× 4` characters in the rule — see `reasoning-budget.ts`).
   * `0` leaves the prelude unbounded; omitted means the config default.
   * A plain profile has no prelude and ignores it. The forced final
   * step lifts the bound per request (`withUnboundedReasoningPrelude`).
   */
  reasoningBudgetTokens?: number;
}

export async function buildGrammar(
  profile: ModelProfile,
  grammarsDir = resolveDefaultGrammarsDir(),
  options: BuildGrammarOptions = {},
): Promise<string> {
  const baseGrammar = await readFile(
    join(grammarsDir, "tool-call.gbnf"),
    "utf8",
  );
  const withBrowser =
    options.browserEnabled === false
      ? removeBrowserToolRule(baseGrammar)
      : baseGrammar;
  const withMcp = applyMcpToolNameRule(
    withBrowser,
    options.mcpToolNameRule ?? null,
  );
  if (!profile.allowThinkPrelude || profile.reasoningStyle === "none")
    return withMcp;
  const ruleStem = profile.id === "gemma4-think" ? "channel" : "think";
  // After thinking, the model emits the array-only form (always `[`).
  // This avoids the GBNF first-token bias toward `{` that small models
  // exhibit even when their `<think>` block reasoned about parallelism.
  const rootRule = `root ::= ${ruleStem}-prelude tool-call-array`;
  const withPreludeRoot = hardenStringRule(
    withMcp.replace(/^root ::= .*$/m, rootRule),
  );
  // When the model emits its own reasoning open tag (Gemma 4 turn-framing),
  // the prelude must force that opener — the prompt no longer prefills it.
  const openSentinel = reasoningOpenEmittedByModel(profile)
    ? profile.reasoningOpenTag
    : undefined;
  // The prelude body is bounded by the reasoning budget (F49): past it
  // the sampler admits only the close sentinel, so a model that would
  // think for 22 minutes is made to close the block and emit the call.
  const preludeRules = buildReasoningPreludeRules(
    ruleStem,
    profile.reasoningCloseTag,
    openSentinel,
    reasoningBudgetChars(
      options.reasoningBudgetTokens ?? DEFAULT_REASONING_BUDGET_TOKENS,
    ),
  );
  return `${withPreludeRoot.trimEnd()}\n${preludeRules}\n`;
}

/** The base grammar's string-body rule, `string ::= "\"" chars "\""`. */
const CHARS_RULE_RE = /^chars ::= char\*$/m;

/**
 * The string body for a reasoning profile: valid JSON with the
 * two-character sequences `<|` and `|>` excluded (F37). The model's own
 * control markers open with one and close with the other (`<|channel>`,
 * `<channel|>`, `<|turn>`, `<turn|>`, `<|im_start|>`), and the grammar
 * admits those bytes nowhere but inside a JSON string — so a thought
 * block that opens mid-call lands in an argument value, and the tool
 * runs on it. With the sequences gone from the sampler's vocabulary the
 * marker cannot be emitted there at all; `control-marker-guard.ts`
 * still refuses whatever arrives another way (an escaped `<|`, a
 * provider without grammars).
 *
 * One exception (ATO-800): `|>` after whitespace (a space, or an escaped
 * `\n`, `\r` or `\t`). Every close marker has a name character right
 * before its `|>` (`channel|>`, `turn|>`, `im_end|>`), while the pipe
 * operator in code (`x |> f` in Elixir, F#, OCaml, R, Hack) is written
 * with a space or at the start of an indented line. Without it a
 * thinking model rewrote the pipe as `| >` or `||`. `<|` stays excluded
 * everywhere.
 *
 * A four-state automaton over the last character — neutral, after
 * whitespace, after `<`, after `|` — rather than the tempting
 * `"<" [^|] | "|" [^>]` alternatives: those let `<<|` and `||>` through
 * (the first `<` pairs with the second, freeing the `|`). A `|` after
 * whitespace lands in neutral, where `>` is plain; a second `|` is back
 * in after-`|`, so ` ||>` stays refused. Whitespace escapes are split
 * from the other escapes so every alternative is still decided by one
 * character: the sampler carries one stack per string, and the right
 * recursion is the same shape llama.cpp expands `char*` into. Only the
 * reasoning profiles get it; the plain profile's grammar stays
 * byte-identical to `grammars/tool-call.gbnf`.
 */
const HARDENED_STRING_RULES = [
  "chars ::= str-neutral",
  'str-neutral ::= ( str-step | "|" str-after-bar )?',
  'str-after-ws ::= ( str-step | "|" str-neutral )?',
  "str-after-lt ::= str-step?",
  'str-after-bar ::= ( str-plain-not-gt str-neutral | str-ws str-after-ws | "<" str-after-lt | "|" str-after-bar )?',
  'str-step ::= str-plain str-neutral | str-ws str-after-ws | "<" str-after-lt',
  String.raw`str-plain ::= [^"\\\x00-\x1f<| ] | str-escape`,
  String.raw`str-plain-not-gt ::= [^"\\\x00-\x1f<|> ] | str-escape`,
  String.raw`str-ws ::= " " | "\\" [nrt]`,
  String.raw`str-escape ::= "\\" ( ["\\/bf] | "u" hex hex hex hex )`,
].join("\n");

/**
 * The same F37 exclusion for the reply body (#681). `reply-text` is its
 * own automaton (the string may not close right after a soft character,
 * see `grammars/tool-call.gbnf`), so it does not go through `chars` and
 * needs the `<|` / `|>` states folded into it. The states multiply: the
 * plain pair (`reply-chars` may close, `reply-pending` may not) gains
 * after-`<` and after-`|`, and `<` / `|` count as hard characters (the
 * string may close after them), so a soft character still leads to
 * `reply-pending` from any state.
 *
 * The ATO-800 whitespace exception splits whitespace out of both
 * classes: a space is soft (`reply-pending-ws`, may not close), an
 * escaped `\n` / `\r` / `\t` is hard (`reply-chars-ws`, may close),
 * and from either a `|` lands in `reply-chars`, where `>` is a plain
 * hard character.
 */
const HARDENED_REPLY_RULES: ReadonlyArray<[RegExp, string]> = [
  [
    /^reply-chars ::= .*$/m,
    [
      'reply-chars ::= ( reply-step | "|" reply-after-bar )?',
      'reply-chars-ws ::= ( reply-step | "|" reply-chars )?',
      'reply-pending-ws ::= reply-step | "|" reply-chars',
      "reply-after-lt ::= reply-step?",
      'reply-after-bar ::= ( reply-hard-not-gt reply-chars | reply-soft reply-pending | " " reply-pending-ws | reply-ws-escape reply-chars-ws | "<" reply-after-lt | "|" reply-after-bar )?',
      'reply-step ::= reply-hard reply-chars | reply-soft reply-pending | " " reply-pending-ws | reply-ws-escape reply-chars-ws | "<" reply-after-lt',
    ].join("\n"),
  ],
  [
    /^reply-pending ::= .*$/m,
    'reply-pending ::= reply-step | "|" reply-after-bar',
  ],
  [
    /^reply-hard ::= .*$/m,
    [
      String.raw`reply-hard ::= [^"\\\x00-\x1f<| :(\[{=,] | str-escape`,
      String.raw`reply-hard-not-gt ::= [^"\\\x00-\x1f<|> :(\[{=,] | str-escape`,
      String.raw`reply-ws-escape ::= "\\" [nrt]`,
    ].join("\n"),
  ],
  [/^reply-soft ::= .*$/m, String.raw`reply-soft ::= [:(\[{=,]`],
];

function hardenStringRule(grammar: string): string {
  let hardened = grammar.replace(CHARS_RULE_RE, HARDENED_STRING_RULES);
  for (const [re, rules] of HARDENED_REPLY_RULES) {
    hardened = hardened.replace(re, rules);
  }
  return hardened;
}

/** The one rule a per-request grammar rewrites. */
const TOOL_NAME_RULE_RE = /^tool-name ::= .*$/m;

/** Terminal verb every restricted grammar keeps: a step must be able to exit. */
const GRAMMAR_EXIT_TOOL = "reply";

/**
 * The split `tool-call` rule of a grammar whose `reply` has its own branch
 * (#681): `reply-call` carries reply with the guarded text rule, and
 * `tool-name` (the generic branch) does not list it. An older grammar
 * without the split keeps `reply` in `tool-name`. `shell-call` is the same
 * idea for `os.shell.run`, whose `cmd` must be a non-empty string; it is
 * optional here so a grammar from before that branch still narrows.
 */
const SPLIT_TOOL_CALL_RULE_RE = /^tool-call ::= reply-call( \| shell-call)?( \| other-call)?$/m;

/** Tools with a dedicated branch of the split rule, outside `tool-name`. */
const SHELL_TOOL = "os.shell.run";

/** `tool-call` when `reply` is the only name a request admits. */
const REPLY_ONLY_TOOL_CALL_RULE_RE = /^tool-call ::= reply-call$/m;

/**
 * Bound on cached per-request grammars per base grammar. The name sets a
 * session cycles through are few (a role, the same role minus the gate's
 * refusals, the two terminals), so the cache is small in practice; the
 * bound only stops a pathological caller from growing it without limit.
 */
const GRAMMAR_CACHE_PER_BASE = 64;
/**
 * Bases seen at once: the live profile's grammar and its two per-request
 * prelude variants (unbounded for the final step, prelude-less under
 * `thinking: off` — `reasoning-prelude.ts`), plus a refresh or two.
 */
const GRAMMAR_CACHE_BASES = 8;

const perRequestGrammarCache = new Map<string, Map<string, string>>();

/**
 * The grammar for ONE request: `baseGrammar` (a `buildGrammar` product —
 * root, reasoning prelude, MCP rule and all) with its `tool-name` rule
 * replaced by a flat alternation over `names`. Everything else is
 * byte-identical to the base, so the reasoning prelude and the JSON body
 * rules the profile invariants pin are untouched.
 *
 * This is how a step narrows what a local model can emit without touching
 * the prompt: the grammar travels with each request and is not part of the
 * KV-cached prefix, so a tool can vanish from the sampler's vocabulary while
 * its descriptor stays in `### tools`. Three callers: an orchestrator turn
 * (everything minus what the fusion gate would refuse — a refusal the model
 * cannot generate is one it cannot spend 20 minutes writing), the final
 * step (`reply` / `finish` only) and a worker or role-restricted turn.
 *
 * `reply` is always present: a grammar with no exit would trap the step in
 * the only thing it can still emit. It lives on its own `reply-call`
 * branch (#681), so `tool-name` gets the other names; when there are none,
 * `tool-call` is cut down to that branch. The rewritten rule is sorted and
 * deduplicated, and the result is cached by the sorted name list, so the
 * same set costs one string build per base grammar.
 */
export function buildGrammarForTools(
  baseGrammar: string,
  names: Iterable<string>,
): string {
  const sorted = Array.from(new Set([...names, GRAMMAR_EXIT_TOOL])).sort();
  const key = sorted.join("\n");
  let perBase = perRequestGrammarCache.get(baseGrammar);
  if (perBase === undefined) {
    if (perRequestGrammarCache.size >= GRAMMAR_CACHE_BASES) {
      const oldest = perRequestGrammarCache.keys().next();
      if (!oldest.done) perRequestGrammarCache.delete(oldest.value);
    }
    perBase = new Map();
    perRequestGrammarCache.set(baseGrammar, perBase);
  }
  const cached = perBase.get(key);
  if (cached !== undefined) return cached;
  const built = SPLIT_TOOL_CALL_RULE_RE.test(baseGrammar)
    ? narrowSplitGrammar(baseGrammar, sorted)
    : replaceToolNameRule(baseGrammar, sorted);
  if (perBase.size >= GRAMMAR_CACHE_PER_BASE) {
    const oldest = perBase.keys().next();
    if (!oldest.done) perBase.delete(oldest.value);
  }
  perBase.set(key, built);
  return built;
}

function replaceToolNameRule(grammar: string, names: string[]): string {
  const rule = `tool-name ::= ${names.map(quoteToolNameLiteral).join(" | ")}`;
  return TOOL_NAME_RULE_RE.test(grammar)
    ? grammar.replace(TOOL_NAME_RULE_RE, rule)
    : // A base without the rule (an older grammar file): a later
      // definition wins in GBNF, so appending still restricts.
      `${grammar.trimEnd()}\n${rule}\n`;
}

/**
 * The per-request rewrite of a split grammar: `reply` stays on its own
 * branch, `os.shell.run` keeps its own branch when the request admits it
 * (and the base grammar has one), `tool-name` lists the other names. A
 * branch with nothing to carry is dropped from `tool-call` (an empty
 * alternation is not valid GBNF); `tool-name` is then left as it was, an
 * unreferenced rule llama.cpp still parses.
 */
function narrowSplitGrammar(grammar: string, names: string[]): string {
  const hasShellBranch = /^shell-call ::= /m.test(grammar);
  const keepShell = hasShellBranch && names.includes(SHELL_TOOL);
  const others = names.filter(
    (name) => name !== GRAMMAR_EXIT_TOOL && !(hasShellBranch && name === SHELL_TOOL),
  );
  const branches = ["reply-call"];
  if (keepShell) branches.push("shell-call");
  if (others.length > 0) branches.push("other-call");
  const narrowed = grammar.replace(SPLIT_TOOL_CALL_RULE_RE, `tool-call ::= ${branches.join(" | ")}`);
  return others.length > 0 ? replaceToolNameRule(narrowed, others) : narrowed;
}

/**
 * The tool names a grammar admits when its `tool-name` rule is a flat
 * alternation of literals (the shape `buildGrammarForTools` writes),
 * sorted, with `reply` included when the grammar carries it on its own
 * `reply-call` branch. `null` for the static base grammar, whose rule is
 * composed of sub-rules. A test helper more than a runtime one.
 */
export function grammarToolNames(grammar: string): string[] | null {
  if (REPLY_ONLY_TOOL_CALL_RULE_RE.test(grammar)) return [GRAMMAR_EXIT_TOOL];
  const split = grammar.match(SPLIT_TOOL_CALL_RULE_RE);
  const names: string[] = [];
  if (!split || split[2] !== undefined) {
    const match = grammar.match(TOOL_NAME_RULE_RE);
    if (!match) return null;
    const body = match[0].slice("tool-name ::= ".length);
    for (const alt of body.split("|")) {
      const literal = alt.trim().match(/^"\\"(.*)\\""$/);
      if (!literal) return null;
      names.push(literal[1]!);
    }
  }
  if (split) names.push(GRAMMAR_EXIT_TOOL);
  if (split?.[1] !== undefined) names.push(SHELL_TOOL);
  return Array.from(new Set(names)).sort();
}

/** `os.fs.read` → `"\"os.fs.read\""` — a JSON string literal inside a GBNF one. */
function quoteToolNameLiteral(name: string): string {
  return quoteGbnf(`"${name}"`);
}

/**
 * Drop the `browser-tool` alternative from the `tool-name ::= ...` rule so the
 * constrained sampler can never emit a `browser.*` call. The `browser-tool ::=`
 * definition line is left in place (an unreferenced rule is harmless in GBNF)
 * to keep the diff minimal and the rest of the file byte-stable.
 */
function removeBrowserToolRule(grammar: string): string {
  return grammar.replace(/^(tool-name ::= ).*$/m, (line, prefix: string) => {
    const alternatives = line
      .slice(prefix.length)
      .split("|")
      .map((alt) => alt.trim())
      .filter((alt) => alt.length > 0 && alt !== "browser-tool");
    return `${prefix}${alternatives.join(" | ")}`;
  });
}
