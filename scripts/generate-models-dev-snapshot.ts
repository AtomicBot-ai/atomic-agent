/**
 * Refresh the bundled models.dev snapshot (ATO-647).
 *
 *   npm run models:snapshot              # fetch https://models.dev/api.json
 *   npm run models:snapshot -- api.json  # or read a saved copy
 *
 * Keeps only the services our presets reach (`MODELS_DEV_PROVIDER_IDS`)
 * and, per model, only what pricing and sizing read: the context and
 * output limits and the per-1M-token prices. Models that do not produce
 * text, or publish no context limit, are dropped. A price of zero in and
 * zero out is dropped too: models.dev uses it for "not listed", and an
 * unknown price must stay unknown rather than read as free.
 *
 * models.dev data is MIT licensed; see THIRD-PARTY-NOTICES.md.
 */
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

import { MODELS_DEV_PROVIDER_IDS } from "../src/llm/provider/models-dev/models-dev-ids.js";

const SOURCE_URL = "https://models.dev/api.json";
const OUT_PATH = fileURLToPath(
  new URL("../src/llm/provider/models-dev/models-dev-snapshot.ts", import.meta.url),
);

type Row = {
  context: number;
  output?: number;
  cost?: { input: number; output: number; cacheRead?: number; cacheWrite?: number };
};

async function loadApi(source: string | undefined): Promise<Record<string, unknown>> {
  if (source !== undefined) return JSON.parse(await readFile(source, "utf8")) as Record<string, unknown>;
  const response = await fetch(SOURCE_URL);
  if (!response.ok) throw new Error(`${SOURCE_URL}: HTTP ${response.status}`);
  return (await response.json()) as Record<string, unknown>;
}

const num = (value: unknown): number | undefined =>
  typeof value === "number" && Number.isFinite(value) && value >= 0 ? value : undefined;

const asRecord = (value: unknown): Record<string, unknown> | undefined =>
  value !== null && typeof value === "object" && !Array.isArray(value)
    ? (value as Record<string, unknown>)
    : undefined;

export function toRow(model: Record<string, unknown>): Row | undefined {
  const outputs = asRecord(model.modalities)?.output;
  if (Array.isArray(outputs) && !outputs.includes("text")) return undefined;
  const limit = asRecord(model.limit);
  const context = num(limit?.context);
  if (context === undefined || context === 0) return undefined;
  const row: Row = { context };
  const output = num(limit?.output);
  if (output !== undefined && output > 0) row.output = output;
  const cost = asRecord(model.cost);
  const input = num(cost?.input);
  const out = num(cost?.output);
  if (input !== undefined && out !== undefined && input + out > 0) {
    const cacheRead = num(cost?.cache_read);
    const cacheWrite = num(cost?.cache_write);
    row.cost = {
      input,
      output: out,
      ...(cacheRead === undefined ? {} : { cacheRead }),
      ...(cacheWrite === undefined ? {} : { cacheWrite }),
    };
  }
  return row;
}

export function renderSnapshot(api: Record<string, unknown>, date: string): string {
  const lines: string[] = [];
  for (const providerId of MODELS_DEV_PROVIDER_IDS) {
    const models = asRecord(asRecord(api[providerId])?.models);
    if (models === undefined) continue;
    const rows = Object.keys(models)
      .sort()
      .map((id) => [id, toRow(asRecord(models[id]) ?? {})] as const)
      .filter((pair): pair is readonly [string, Row] => pair[1] !== undefined);
    if (rows.length === 0) continue;
    lines.push(`  ${JSON.stringify(providerId)}: {`);
    for (const [id, row] of rows) lines.push(`    ${JSON.stringify(id)}: ${JSON.stringify(row)},`);
    lines.push("  },");
  }
  return [
    "// Generated by scripts/generate-models-dev-snapshot.ts from",
    `// ${SOURCE_URL} (MIT, see THIRD-PARTY-NOTICES.md). Do not edit by hand:`,
    "// run `npm run models:snapshot` instead.",
    "",
    "export type ModelsDevRow = {",
    "  readonly context: number;",
    "  readonly output?: number;",
    "  readonly cost?: {",
    "    readonly input: number;",
    "    readonly output: number;",
    "    readonly cacheRead?: number;",
    "    readonly cacheWrite?: number;",
    "  };",
    "};",
    "",
    `export const MODELS_DEV_SNAPSHOT_DATE = ${JSON.stringify(date)};`,
    "",
    "/** models.dev slug -> model id -> limits and per-1M-token USD prices. */",
    "export const MODELS_DEV_SNAPSHOT: Readonly<",
    "  Record<string, Readonly<Record<string, ModelsDevRow>>>",
    "> = {",
    ...lines,
    "};",
    "",
  ].join("\n");
}

async function main(): Promise<void> {
  const api = await loadApi(process.argv[2]);
  const date = new Date().toISOString().slice(0, 10);
  await writeFile(OUT_PATH, renderSnapshot(api, date));
  process.stdout.write(`wrote ${OUT_PATH}\n`);
}

if (process.argv[1] !== undefined && fileURLToPath(import.meta.url) === process.argv[1]) {
  await main();
}
